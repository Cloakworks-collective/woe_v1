// The Elder Ages — the sealed history of the old realm (War of Empires,
// 2005–2013), 32 ages long. War of Empires is the modern iteration of that
// game; these chronicles are its legend, kept forever in the Annals.
//
// In every age the crown fell to the age's supreme power (the top player early
// on, the top empire later), who then lent their name to the NEXT age — as the
// eras run today. The data is the real historical record, shown in full tables;
// the lore framing is written in the scribes' tongue. Append later ages to
// ELDER_AGES as records surface.

/** A table cell: a plain value, or a linked label (e.g. a clan → its page). */
export type ElderCell = string | number | { text: string; href: string };

/** A generic leaderboard from the old chronicles. */
export interface ElderTable {
  title: string;
  headers: string[];
  rows: ElderCell[][];
  note?: string; // e.g. "champion of each feat"
  numeric?: number[]; // indices of right-aligned numeric columns
}

export interface ElderAge {
  age: number;
  name: string; // "The Age of IronFist" (named for the prior victor)
  span: string;
  victor: string; // the age's supreme power — a ruler, or (later ages) an empire
  victorRace?: string;
  victorIsEmpire?: boolean; // true when the crown fell to an empire, not a player
  topRuler?: { name: string; clan?: string; race?: string }; // the age's #1 individual, when an empire took the crown
  lore: string; // a scribe's colourful summary of the age
  tables: ElderTable[];
}

// The victory rule changed across the 32 ages, so the chronicles fall into four
// eras. Each age belongs to exactly one (by its number).
export interface ChronicleGroup {
  key: string;
  ageLabel: string;
  min: number;
  max: number;
  title: string;
  rule: string;
  crownLabel: string;
}

